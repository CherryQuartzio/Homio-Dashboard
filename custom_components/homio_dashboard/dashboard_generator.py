_LOGGER = logging.getLogger(__name__)

_GENERATED_HEADER = (
    "# GENERATED by Homio Dashboard — edit via Settings → Devices & Services → Homio.\n"
    "# Manual edits will be overwritten on reload.\n"
)


def layout_dir(hass: HomeAssistant) -> Path:
    """Return /config/homio/layout."""
    return Path(hass.config.path(USER_HOMIO_DIR)) / USER_LAYOUT_DIR


def sections_path(hass: HomeAssistant) -> Path:
    """Return path to generated sections.yaml."""
    return layout_dir(hass) / USER_SECTIONS_FILE


def navigation_path(hass: HomeAssistant) -> Path:
    """Return path to generated navigation.yaml."""
    return layout_dir(hass) / USER_NAVIGATION_FILE


def generated_root(hass: HomeAssistant) -> Path:
    """Return /config/homio/layout/_generated."""
    return layout_dir(hass) / USER_GENERATED_DIR


def icon_for_entity(entity_id: str) -> str | None:
    """Return default Homio icon stem for an entity domain."""
    domain = entity_id.split(".", 1)[0]
    if domain in DOMAIN_ICON_MAP:
        return DOMAIN_ICON_MAP[domain]
    return DEFAULT_DEVICE_ICON


def card_template_for_entity(entity_id: str) -> str:
    """Return button-card template name for an entity."""
    domain = entity_id.split(".", 1)[0]
    if domain == "climate":
        return "homio_thermostat"
    if domain == "light":
        return "homio_light"
    return "homio_entity"


def room_slug(nav_name: str) -> str:
    """Infer Homio view path slug from a nav name."""
    slug = ha_slugify(nav_name.strip())
    return slug or "room"


def merge_devices(
    entity_ids: list[str],
    previous: list[dict[str, Any]] | None,
) -> list[dict[str, Any]]:
    """Build ordered device dicts; preserve icons; auto-map new entities."""
    prev_by_entity = {
        str(item.get(CONF_DEVICE_ENTITY)): item
        for item in (previous or [])
        if isinstance(item, dict) and item.get(CONF_DEVICE_ENTITY)
    }
    result: list[dict[str, Any]] = []
    for entity_id in entity_ids:
        if not entity_id:
            continue
        if entity_id in prev_by_entity:
            prev = prev_by_entity[entity_id]
            icon = prev.get(CONF_DEVICE_ICON)
            result.append({CONF_DEVICE_ENTITY: entity_id, CONF_DEVICE_ICON: icon})
        else:
            result.append(
                {
                    CONF_DEVICE_ENTITY: entity_id,
                    CONF_DEVICE_ICON: icon_for_entity(entity_id),
                }
            )
    return result


def room_subentries(entry: ConfigEntry) -> list[ConfigSubentry]:
    """Return room subentries for the Homio config entry."""
    return [
        sub
        for sub in entry.subentries.values()
        if sub.subentry_type == SUBENTRY_TYPE_ROOM
    ]


def ordered_rooms(entry: ConfigEntry) -> list[dict[str, Any]]:
    """Return room data dicts sorted for generation (nav order first)."""
    rooms = []
    for sub in room_subentries(entry):
        data = dict(sub.data)
        data.setdefault(CONF_SLUG, room_slug(str(data.get(CONF_NAV_NAME, sub.title))))
        data.setdefault(CONF_NAV_NAME, sub.title)
        rooms.append(data)

    by_slug: dict[str, dict[str, Any]] = {}
    for room in rooms:
        slug = room[CONF_SLUG]
        if slug in by_slug:
            _LOGGER.warning(
                "Duplicate Homio room slug %s (%s); keeping first room only",
                slug,
                room.get(CONF_NAV_NAME),
            )
            continue
        by_slug[slug] = room

    nav_order = list(entry.options.get(CONF_NAV_ORDER, []))
    ordered: list[dict[str, Any]] = []
    seen: set[str] = set()
    for slug in nav_order:
        if slug in by_slug and slug not in seen:
            ordered.append(by_slug[slug])
            seen.add(slug)
    for slug, room in by_slug.items():
        if slug not in seen:
            ordered.append(room)
            seen.add(slug)
    return ordered


def collect_friendly_names(hass: HomeAssistant, entry: ConfigEntry) -> dict[str, str]:
    """Resolve device display names on the event loop (not in an executor)."""
    names: dict[str, str] = {}
    for room in ordered_rooms(entry):
        for device in room.get(CONF_DEVICES) or []:
            if not isinstance(device, dict):
                continue
            entity_id = device.get(CONF_DEVICE_ENTITY)
            if not entity_id or entity_id in names:
                continue
            names[str(entity_id)] = _friendly_name(hass, str(entity_id))
    return names


def _yaml_scalar(value: Any) -> str:
    """Format a YAML scalar; always quote strings to avoid inject/coerce bugs."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return str(value)
    # Force single-quoted scalar so !, -, @, %, on/off, etc. stay literal text.
    return yaml.dump(
        str(value), default_style="'", default_flow_style=True
    ).strip()


def _indent(text: str, spaces: int) -> str:
    pad = " " * spaces
    return "\n".join(pad + line if line else line for line in text.splitlines())


def _friendly_name(hass: HomeAssistant, entity_id: str) -> str:
    state = hass.states.get(entity_id)
    if state and state.attributes.get("friendly_name"):
        return str(state.attributes["friendly_name"])
    return _fallback_entity_name(entity_id)


def _fallback_entity_name(entity_id: str) -> str:
    if "." in entity_id:
        return entity_id.split(".", 1)[1].replace("_", " ").title()
    return entity_id


def _device_card_yaml(
    device: dict[str, Any], friendly_names: dict[str, str]
) -> str:
    entity_id = str(device[CONF_DEVICE_ENTITY])
    template = card_template_for_entity(entity_id)
    name = friendly_names.get(entity_id) or _fallback_entity_name(entity_id)
    icon = device.get(CONF_DEVICE_ICON)
    lines = [
        "- type: custom:button-card",
        "  template:",
        f"    - {template}",
        f"  entity: {_yaml_scalar(entity_id)}",
        f"  name: {_yaml_scalar(name)}",
    ]
    if template != "homio_thermostat" and icon:
        lines.extend(
            [
                "  variables:",
                f"    icon: {_yaml_scalar(icon)}",
            ]
        )
    return "\n".join(lines)


def _room_view_yaml(
    room: dict[str, Any],
    includes_abs: str,
    friendly_names: dict[str, str],
) -> str:
    slug = room[CONF_SLUG]
    nav_name = room.get(CONF_NAV_NAME, slug)
    display = room.get(CONF_DISPLAY_NAME) or nav_name
    image = room.get(CONF_IMAGE) or slug
    image_position = room.get(CONF_IMAGE_POSITION) or DEFAULT_IMAGE_POSITION
    show_temp = bool(room.get(CONF_SHOW_TEMP, False))
    show_humid = bool(room.get(CONF_SHOW_HUMID, False))
    show_motion = bool(room.get(CONF_SHOW_MOTION, False))
    temp_sensor = room.get(CONF_TEMP_SENSOR)
    humid_sensor = room.get(CONF_HUMID_SENSOR)
    motion_sensor = room.get(CONF_MOTION_SENSOR)
    devices = room.get(CONF_DEVICES) or []

    device_blocks = [
        _indent(_device_card_yaml(d, friendly_names), 16)
        for d in devices
        if isinstance(d, dict) and d.get(CONF_DEVICE_ENTITY)
    ]
    if device_blocks:
        cards_yaml = "              cards:\n" + "\n".join(device_blocks)
    else:
        cards_yaml = "              cards: []"

    return f"""  - type: custom:grid-layout
    title: {_yaml_scalar(nav_name)}
    path: {_yaml_scalar(slug)}
    theme: homio
    layout: !include {includes_abs}/homio_screen_layout.yaml
    cards:
      - type: custom:button-card
        template:
          - homio_room
        name: {_yaml_scalar(display)}
        variables:
          image: {_yaml_scalar(image)}
          image_position: {_yaml_scalar(image_position)}
          show_temp: {_yaml_scalar(show_temp)}
          show_humid: {_yaml_scalar(show_humid)}
          show_motion: {_yaml_scalar(show_motion)}
          motion_sensor: {_yaml_scalar(motion_sensor)}
          temp_sensor: {_yaml_scalar(temp_sensor)}
          humid_sensor: {_yaml_scalar(humid_sensor)}
        custom_fields:
          entities:
            card:
              type: custom:layout-card
              layout_type: custom:grid-layout
              layout: !include {includes_abs}/homio_entity_layout.yaml
{cards_yaml}
"""


def _navigation_yaml(rooms: list[dict[str, Any]]) -> str:
    blocks: list[str] = []
    for room in rooms:
        if not room.get(CONF_SHOW_IN_NAVIGATION, True):
            continue
        slug = room[CONF_SLUG]
        nav_name = room.get(CONF_NAV_NAME, slug)
        blocks.append(
            f"""- type: custom:button-card
  template:
    - homio_nav_button
  name: {_yaml_scalar(nav_name)}
  variables:
    path: /{DOMAIN}/{slug}
"""
        )
    return _GENERATED_HEADER + ("\n".join(blocks) if blocks else "[]\n")


