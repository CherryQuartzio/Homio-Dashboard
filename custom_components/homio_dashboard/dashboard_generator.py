class _IgnoreIncludeLoader(yaml.SafeLoader):
    """YAML loader that treats !include* as null so views still parse."""


def _ignore_include(loader: yaml.SafeLoader, node: yaml.Node) -> None:
    return None


_IgnoreIncludeLoader.add_constructor("!include", _ignore_include)
_IgnoreIncludeLoader.add_constructor("!include_dir_merge_named", _ignore_include)
_IgnoreIncludeLoader.add_constructor("!include_dir_named", _ignore_include)
_IgnoreIncludeLoader.add_constructor("!include_dir_list", _ignore_include)
_IgnoreIncludeLoader.add_constructor("!include_dir_merge_list", _ignore_include)


def parse_rooms_from_homio_yaml(path: Path) -> list[dict[str, Any]]:
    """Best-effort parse room configs from a Homio lovelace YAML file."""
    if not path.is_file():
        return []
    try:
        data = yaml.load(path.read_text(encoding="utf-8"), Loader=_IgnoreIncludeLoader)
    except Exception as err:  # noqa: BLE001
        _LOGGER.warning("Failed to parse Homio YAML at %s: %s", path, err)
        return []
    if not isinstance(data, dict):
        return []
    views = data.get("views") or []
    rooms: list[dict[str, Any]] = []
    for view in views:
        if not isinstance(view, dict):
            continue
        path_slug = view.get("path")
        title = view.get("title") or path_slug
        if not path_slug:
            continue
        cards = view.get("cards") or []
        room_card = next(
            (
                c
                for c in cards
                if isinstance(c, dict)
                and "homio_room" in (c.get("template") or [])
            ),
            None,
        )
        if not room_card:
            room_card = cards[0] if cards and isinstance(cards[0], dict) else {}
        variables = room_card.get("variables") or {}
        devices: list[dict[str, Any]] = []
        entities_card = (
            ((room_card.get("custom_fields") or {}).get("entities") or {}).get("card")
            or {}
        )
        for device_card in entities_card.get("cards") or []:
            if not isinstance(device_card, dict):
                continue
            entity_id = device_card.get("entity")
            if not entity_id:
                continue
            icon = (device_card.get("variables") or {}).get("icon")
            if icon is None:
                icon = icon_for_entity(str(entity_id))
            devices.append(
                {CONF_DEVICE_ENTITY: str(entity_id), CONF_DEVICE_ICON: icon}
            )
        rooms.append(
            {
                CONF_NAV_NAME: str(title),
                CONF_SLUG: str(path_slug),
                CONF_DISPLAY_NAME: room_card.get("name") or str(title),
                CONF_SHOW_IN_NAVIGATION: True,
                CONF_IMAGE: variables.get("image") or path_slug,
                CONF_IMAGE_POSITION: variables.get("image_position")
                or DEFAULT_IMAGE_POSITION,
                CONF_SHOW_TEMP: bool(variables.get("show_temp", False)),
                CONF_TEMP_SENSOR: variables.get("temp_sensor"),
                CONF_SHOW_HUMID: bool(variables.get("show_humid", False)),
                CONF_HUMID_SENSOR: variables.get("humid_sensor"),
                CONF_SHOW_MOTION: bool(variables.get("show_motion", False)),
                CONF_MOTION_SENSOR: variables.get("motion_sensor"),
                CONF_DEVICES: devices,
            }
        )
    return rooms


def parse_logo_from_templates(integration_dir: Path) -> tuple[str, str | None]:
    """Read logo name and home path from bundled logo templates."""
    logo_path = (
        integration_dir
        / "dashboards"
        / "templates"
        / "button_cards"
        / "base"
        / "homio_logo.yaml"
    )
    logo_name = DEFAULT_LOGO_NAME
    home_slug: str | None = None
    if logo_path.is_file():
        try:
            data = yaml.safe_load(logo_path.read_text(encoding="utf-8")) or {}
            logo = data.get("homio_logo") or {}
            if logo.get("name"):
                logo_name = str(logo["name"])
            nav = (logo.get("tap_action") or {}).get("navigation_path") or ""
            if isinstance(nav, str) and nav.startswith(f"/{DOMAIN}/"):
                home_slug = nav[len(f"/{DOMAIN}/") :].strip("/") or None
        except Exception as err:  # noqa: BLE001
            _LOGGER.debug("Could not parse logo template: %s", err)
    return logo_name, home_slug


def _uniquify_room_slugs(rooms: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Ensure unique slugs within a migration batch."""
    taken: set[str] = set()
    result: list[dict[str, Any]] = []
    for room in rooms:
        slug = str(room.get(CONF_SLUG) or room_slug(str(room.get(CONF_NAV_NAME, "room"))))
        base = slug
        n = 2
        while slug in taken:
            slug = f"{base}_{n}"
            n += 1
        taken.add(slug)
        room = dict(room)
        room[CONF_SLUG] = slug
        result.append(room)
    return result


def read_migration_source(hass: HomeAssistant) -> dict[str, Any]:
    """Read legacy/bundled YAML off the event loop. Returns a plain payload dict."""
    integration_dir = Path(__file__).parent
    # Prefer user-owned dashboards before the bundled Daylor seed.
    candidates = [
        Path(hass.config.path("dashboards")) / "homio" / "homio.yaml",
        Path(hass.config.path("homio")) / "homio.yaml",
        integration_dir / "lovelace" / "homio.yaml",
    ]
    rooms: list[dict[str, Any]] = []
    source: str | None = None
    for path in candidates:
        parsed = parse_rooms_from_homio_yaml(path)
        if parsed:
            rooms = parsed
            source = str(path)
            break

    # Never pull logo text from bundled templates (may be site-specific).
    logo_name = DEFAULT_LOGO_NAME
    home_slug: str | None = None
    if rooms:
        home_slug = str(rooms[0].get(CONF_SLUG) or "") or None

    if not rooms:
        rooms = [
            {
                CONF_NAV_NAME: "Living",
                CONF_SLUG: "living",
                CONF_DISPLAY_NAME: "Living Room",
                CONF_SHOW_IN_NAVIGATION: True,
                CONF_IMAGE: "lounge",
                CONF_IMAGE_POSITION: DEFAULT_IMAGE_POSITION,
                CONF_SHOW_TEMP: False,
                CONF_TEMP_SENSOR: None,
                CONF_SHOW_HUMID: False,
                CONF_HUMID_SENSOR: None,
                CONF_SHOW_MOTION: False,
                CONF_MOTION_SENSOR: None,
                CONF_DEVICES: [],
            }
        ]
        home_slug = "living"
        source = None

    rooms = _uniquify_room_slugs(rooms)
    return {
        "rooms": rooms,
        "logo_name": logo_name,
        "home_slug": home_slug,
        "source": source,
    }


def apply_migration(hass: HomeAssistant, entry: ConfigEntry, payload: dict[str, Any]) -> bool:
    """Apply migration payload on the event loop. Returns True if subentries added."""
    if entry.data.get(CONF_YAML_MIGRATED):
        return False

    if room_subentries(entry):
        hass.config_entries.async_update_entry(
            entry,
            data={**dict(entry.data), CONF_YAML_MIGRATED: True},
        )
        return False

    rooms: list[dict[str, Any]] = list(payload.get("rooms") or [])
    logo_name = str(payload.get("logo_name") or DEFAULT_LOGO_NAME)
    home_slug = payload.get("home_slug")
    source = payload.get("source")
    if source:
        _LOGGER.info("Migrating Homio rooms from %s", source)
    else:
        _LOGGER.info("Seeding Homio with a minimal Living room")

    nav_order = [r[CONF_SLUG] for r in rooms if r.get(CONF_SHOW_IN_NAVIGATION, True)]
    if not home_slug and nav_order:
        home_slug = nav_order[0]

    for room in rooms:
        slug = room[CONF_SLUG]
        hass.config_entries.async_add_subentry(
            entry,
            ConfigSubentry(
                data=room,
                subentry_type=SUBENTRY_TYPE_ROOM,
                title=str(room.get(CONF_NAV_NAME) or slug),
                unique_id=slug,
            ),
        )

    options = {
        **dict(entry.options),
        CONF_LOGO_NAME: entry.options.get(CONF_LOGO_NAME) or logo_name,
        CONF_LOGO_HOME_ROOM: entry.options.get(CONF_LOGO_HOME_ROOM) or (home_slug or ""),
        CONF_NAV_ORDER: entry.options.get(CONF_NAV_ORDER) or nav_order,
    }
    hass.config_entries.async_update_entry(
        entry,
        data={**dict(entry.data), CONF_YAML_MIGRATED: True},
        options=options,
    )
    return True


def migrate_rooms_from_yaml(hass: HomeAssistant, entry: ConfigEntry) -> bool:
    """Backward-compatible sync migrate (I/O + apply). Prefer split helpers."""
    if entry.data.get(CONF_YAML_MIGRATED):
        return False
    if room_subentries(entry):
        hass.config_entries.async_update_entry(
            entry,
            data={**dict(entry.data), CONF_YAML_MIGRATED: True},
        )
        return False
    payload = read_migration_source(hass)
    return apply_migration(hass, entry, payload)
