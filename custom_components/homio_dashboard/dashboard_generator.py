def _patch_navigation_include(includes_dir: Path, nav_file_abs: str) -> None:
    """Copy navigation shell and point list include at generated navigation.yaml."""
    integration_includes = (
        Path(__file__).parent / "dashboards" / "templates" / "includes"
    )
    includes_dir.mkdir(parents=True, exist_ok=True)
    for name in (
        "homio_screen_layout.yaml",
        "homio_entity_layout.yaml",
        "homio_navigation.yaml",
    ):
        src = integration_includes / name
        dest = includes_dir / name
        if not src.is_file():
            continue
        text = src.read_text(encoding="utf-8")
        if name == "homio_navigation.yaml":
            text = text.replace(
                "!include homio_navigation_list.yaml",
                f"!include {nav_file_abs}",
            )
        dest.write_text(text, encoding="utf-8")


def generate_dashboard(
    hass: HomeAssistant,
    entry: ConfigEntry,
    friendly_names: dict[str, str] | None = None,
) -> Path:
    """Write generated layout files and return sections.yaml path."""
    integration_dir = Path(__file__).parent
    layout = layout_dir(hass)
    gen = generated_root(hass)
    button_cards_dest = gen / "button_cards"
    includes_dest = gen / "includes"
    names = friendly_names or {}

    layout.mkdir(parents=True, exist_ok=True)

    # Fresh mirror of button-card templates each generate.
    src_cards = integration_dir / "dashboards" / "templates" / "button_cards"
    if button_cards_dest.exists():
        shutil.rmtree(button_cards_dest)
    shutil.copytree(src_cards, button_cards_dest)

    rooms = ordered_rooms(entry)
    options = entry.options
    logo_name = str(options.get(CONF_LOGO_NAME) or DEFAULT_LOGO_NAME)
    home_slug = str(options.get(CONF_LOGO_HOME_ROOM) or "")
    if not home_slug and rooms:
        home_slug = str(rooms[0].get(CONF_SLUG, ""))

    nav_abs = str(navigation_path(hass)).replace("\\", "/")
    includes_abs = str(includes_dest).replace("\\", "/")
    button_cards_abs = str(button_cards_dest).replace("\\", "/")

    _patch_navigation_include(includes_dest, nav_abs)
    _patch_logo_files(button_cards_dest, logo_name, home_slug)

    navigation_path(hass).write_text(_navigation_yaml(rooms), encoding="utf-8")

    views = "\n".join(
        _room_view_yaml(room, includes_abs, names) for room in rooms
    )
    if not views.strip():
        views = """  - type: custom:grid-layout
    title: Home
    path: home
    theme: homio
    layout: !include {includes}/homio_screen_layout.yaml
    cards:
      - type: markdown
        content: >
          Configure Homio rooms under
          **Settings → Devices & Services → Homio → Add room**.
""".format(includes=includes_abs)

    sections = f"""{_GENERATED_HEADER}
kiosk_mode:
  hide_header: true

button_card_templates: !include_dir_merge_named {button_cards_abs}

views:
{views}
"""
    out = sections_path(hass)
    out.write_text(sections, encoding="utf-8")
    _LOGGER.info("Homio dashboard generated at %s (%s rooms)", out, len(rooms))
    return out


